def _close_variant(image,ram_base,ram_size,spec):
    def word(at):
        return struct.unpack_from('<I',image,at)[0] if 0<=at<=len(image)-4 else None
    for role,at,n,digest,calls,literals,arm in spec['rows']:
        if (not 0<=at<=len(image)-n or hashlib.sha256(image[at:at+n]).hexdigest()!=digest
                or any(thumb_bl_target(image,at+off)!=target for off,target in calls)
                or any(thumb_literal_value(image,at+off,reg)!=value for off,reg,value in literals)):
            return None
        for off,reg,value,pool in arm:
            pc=at+off;op=word(pc)
            if op is None or op&0x0f7f0000!=0x051f0000 or op>>12&15!=reg:
                return None
            resolved=pc+8+((op&0xfff) if op&0x800000 else -(op&0xfff))
            if resolved!=pool or word(pool)!=value:
                return None
    early_at,early=spec['early']
    if not 0<=early_at<=len(image)-32 or struct.unpack_from('<8I',image,early_at)!=early:
        return None
    first_source,first_ram,first_size,early_bss,early_length,iram_source,iram,iram_size=early
    if (any(v&3 for v in early) or not first_size or not early_length or not iram_size
            or not 0<=first_source<=len(image)-first_size
            or not ram_base<=first_ram<=ram_base+ram_size-first_size
            or early_bss!=first_ram+first_size
            or not ram_base<=early_bss<=ram_base+ram_size-early_length
            or not 0<=iram_source<=len(image)-iram_size
            or not 0x03800000<=iram<=0x03a00000-iram_size):
        return None
    copy=spec['copy']
    if _legacy_620_vector_copy(image,ram_base=ram_base,ram_size=ram_size)!=copy:
        return None
    source,target,length,wrapper=copy
    bss_begin,bss_size=spec['bss'];bss_end=bss_begin+bss_size
    if (len(image)<0x6038 or struct.unpack_from('<5I',image,0x6024)!=(
            source,target,length,bss_begin,bss_size)
            or bss_begin!=target+length
            or not ram_base<=target<bss_begin<bss_end<=ram_base+ram_size):
        return None
