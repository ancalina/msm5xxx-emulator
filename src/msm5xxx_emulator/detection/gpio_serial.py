def find_gpio_serial_profile(image: bytes):
    if not isinstance(image, bytes):
        return None, 'gpio-serial-primary-bytes-required'
    for template in _TEMPLATES:
        try:
            profile = _match(image, template)
        except (ValueError, IndexError, struct.error):
            continue
        return profile, 'source-gpio-serial89-candidate'
    return None, 'gpio-serial-source-unclosed'


