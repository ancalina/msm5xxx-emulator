def find_bytepair565_profile(image: bytes):
    if not isinstance(image,bytes):
        return None,'bytepair565-reset-unclosed'
    if arm_b_target(image,0) != 0x1bbc:
        from .bytepair565_mx import find_mx_bytepair565_profile
        return find_mx_bytepair565_profile(image)
    if any(not 0 <= at <= len(image)-size or
           hashlib.sha256(image[at:at+size]).hexdigest() != digest
           for at,size,digest in _SPANS):
        return None,'bytepair565-source-body-unclosed'
    if any(not 0 <= at <= len(image)-4 or struct.unpack_from('<I',image,at)[0] != value
           for at,value in _POOLS):
        return None,'bytepair565-source-pool-unclosed'
    if struct.unpack_from('<6I',image,0x348dd8) != (104,80,16,0x4100,3,0x0104a7b0):
        return None,'bytepair565-descriptor-unclosed'
    return dict(signature='source-halfword-bytepair565-104-v1',admission='temporary-evidence-gated',
        width=104,height=80,pixel_port=0x02400000,command_port=0x02000000,access_width=2,
        code_intervals=((0,4),)+tuple((at,at+size)for at,size,digest in _SPANS),
        literal_intervals=tuple((at,at+4)for at,value in _POOLS),data_intervals=(),
        ram_intervals=_RAM,iram_intervals=((0x03800000,0x0380fbd8),),
        encoding='format3-565-high-byte-first',physical_viewport=None,
        component_naming='conventional-rgb-inferred'), 'source-bytepair565-candidate'
